#!/usr/bin/env python3
"""Generates src/probe/PACFSB.asm (scaled-renderer study, probe E11; isolated from PACMAN, no capability query).
Every 3270 byte comes from tools/scaled_model.py (the same encoder a renderer would use: RA, RA+GE, SBA skips).
Screens (TPUT FULLSCR, WCC + the D25 clear prefix, formatted with a 1-byte input field like the game):
 1 layout A 2x2, 2 layout B 4x2, 3 layout C 3x2 - each at the oracle start position plus 2 extra ghosts and a message,
   followed by 6 partial updates 0.5 s apart (TPUT NOEDIT, X'F1' Write + WCC C2, only the invalidated 2x2/3x2/4x2 cells):
   Pac-Man moves one logical cell right, closes, opens, moves back, closes, opens;
 4 sprite gallery: Pac-Man R/L/shut, ghost frames A/B, 3 ghost colours, pellet, power pellet, for each scale.
ENTER = next screen (after the last: end), PA2 = replay the current screen and its partials.
CALL 'PACFSB' USING RC NSCR NPART AID (all S9(4) COMP except AID X(1)); RC 4 = not a TSO session (nothing sent).
Usage: python3 tools/gen_probe_e11.py   (writes src/probe/PACFSB.asm, prints sizes)"""
import sys
from pathlib import Path

R = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(R / 'tools'))
import scaled_model as m  # noqa: E402

CLEAR = [0x11, 0x40, 0x40, 0x3C, 0x40, 0x40, 0x00]
D = {(1, 1): 'pac', (18, 8): 'ghost1', (9, 3): 'ghost2', (10, 7): 'ghost3'}


def steps():
    """(sprites, frame, face) after each partial; the dirty logical cells are the old and new Pac-Man cells."""
    a, b = dict(D), dict(D)
    del b[(1, 1)]
    b[(2, 1)] = 'pac'
    a[(1, 1)] = 'pac'
    return [(b, 'A', 'R', [(1, 1), (2, 1)]), (b, 'B', 'R', [(2, 1)]), (b, 'A', 'R', [(2, 1)]),
            (a, 'A', 'L', [(1, 1), (2, 1)]), (a, 'B', 'L', [(1, 1)]), (a, 'A', 'L', [(1, 1)])]


def full_bytes(scr):
    s = m.encode(scr)
    return bytes([s[0]] + CLEAR) + s[1:]


def layout_screen(name, n):
    sizes = {}
    for _ in range(2):       # second pass puts the real size into the label
        lab = f'E11 {n}/4 LAYOUT {name} {m.LAYOUTS[name]["scale"][0]}X{m.LAYOUTS[name]["scale"][1]} ' \
              f'{sizes.get(name, 0):04d} B'
        scr = m.layout(name, D, msg='ENTER NEXT  PA2 REPLAY', label=lab)
        sizes[name] = len(m.encode(scr))
    parts = []
    for spr, frame, face, cells in steps():
        dirty = set()
        for x, y in cells:
            dirty |= m.logical_cells(name, x, y)
        after = m.layout(name, spr, frame, face, msg='ENTER NEXT  PA2 REPLAY', label=lab)
        parts.append(bytes([0xF1]) + m.encode(after, 0xC2, dirty, full=False))
    return full_bytes(scr), parts, sizes[name]


def gallery():
    scr = m.Screen()
    scr.sf(1, 1, 0x60)
    scr.put(1, 2, 'E11 4/4 SPRITE GALLERY (PIXELS = HALF BLOCKS, FULL = REVERSE VIDEO)', m.TURQ)
    scr.put(2, 2, 'ORDER: PAC R, PAC L, PAC SHUT, GHOST A, GHOST B, PINK, TURQ, PELLET, POWER', m.GREEN)
    row = 4
    for sx, sy in ((2, 2), (3, 2), (4, 2)):
        scr.put(row, 2, f'{sx}X{sy}', m.GREEN)
        col = 9
        items = [('pac', 'A', 'R'), ('pac', 'A', 'L'), ('pac', 'B', 'R'), ('ghost1', 'A', 'R'), ('ghost1', 'B', 'R'),
                 ('ghost2', 'A', 'R'), ('ghost3', 'A', 'R'), ('pellet', 'A', 'R'), ('power', 'A', 'R')]
        for kind, frame, face in items:
            scr.place(row, col, m.tile(kind, sx, sy, frame, face))
            col += sx + 3
        row += 4
    scr.put(17, 2, 'NOTE: SHAPES, EYES (BLACK ° ON THE GHOST), PROPORTIONS OF EACH SCALE.', m.GREEN)
    scr.input_field(21, 2)
    scr.put(21, 20, 'ENTER = END   PA2 = REDRAW', m.GREEN)
    return full_bytes(scr), [], len(m.encode(scr))


def dc_lines(label, data):
    out, first = [], True
    for k in range(0, len(data), 24):
        out.append(f"{label if first else '':<8} DC    X'{data[k:k + 24].hex().upper()}'")
        first = False
    return out


HEAD = """*        PACFSB : SCALED-RENDERER STUDY, PROBE E11 (GENERATED BY
*        GEN_PROBE_E11.PY, DO NOT EDIT). ISOLATED FROM PACMAN, NO
*        QUERY. 4 FULL SCREENS (TPUT FULLSCR), EACH FOLLOWED BY ITS
*        PARTIAL UPDATES (TPUT NOEDIT, X'F1' WRITE) 0.5 S APART, THEN
*        A KEY: PA2 REPLAYS THE SCREEN, ANY OTHER KEY GOES ON.
*        CALL 'PACFSB' USING RC NSCR NPART AID
PACFSB   CSECT
         STM   14,12,12(13)
         BALR  12,0
         USING *,12
         ST    13,SAVE+4
         LA    14,SAVE
         ST    14,8(13)
         LR    13,14
         LM    2,5,0(1)
         LA    2,0(2)              RC
         LA    3,0(3)              NSCR
         LA    4,0(4)              NPART
         LA    5,0(5)              AID
         SR    14,14
         STH   14,0(3)
         STH   14,0(4)
         MVI   0(5),X'00'
         LA    14,4
         STH   14,0(2)
         L     1,X'224'            PSAAOLD: CURRENT ASCB
         L     1,X'3C'(1)          ASCBTSB: ZERO UNLESS TSO USER
         LTR   1,1
         BZ    DONE
         TCLEARQ OUTPUT
         TCLEARQ INPUT
         STFSMODE ON,INITIAL=YES
         STTMPMD ON
         L     6,=A(SCRTAB)        R6 = CURRENT SCREEN ENTRY
         L     7,=A(NSCRN)         R7 = SCREENS LEFT
SCREEN   DS    0H
         LH    14,0(3)
         LA    14,1(14)
         STH   14,0(3)
         L     1,0(6)              FULL SCREEN ADDRESS
         L     0,4(6)              ITS LENGTH
         TPUT  (1),(0),FULLSCR
         STH   15,0(2)
         LTR   15,15
         BNZ   BACK
         L     8,8(6)              PARTIAL TABLE
         L     9,12(6)             NUMBER OF PARTIALS
         LTR   9,9
         BZ    KEY
PART     DS    0H
         STIMER WAIT,BINTVL=HALFSEC
         L     1,0(8)
         L     0,4(8)
         TPUT  (1),(0),NOEDIT
         STH   15,0(2)
         LTR   15,15
         BNZ   BACK
         LH    14,0(4)
         LA    14,1(14)
         STH   14,0(4)
         LA    8,8(8)
         BCT   9,PART
KEY      DS    0H
         SR    10,10
KREAD    DS    0H
         LA    1,INBUF
         L     0,=F'256'
         TGET  (1),(0),ASIS
         STH   15,0(2)
         LTR   1,1
         BNZ   KGOT
         LA    10,1(10)
         C     10,=F'600'
         BNL   BACK                5 MINUTES WITHOUT A KEY
         STIMER WAIT,BINTVL=HALFSEC
         B     KREAD
KGOT     DS    0H
         MVC   0(1,5),INBUF
         CLI   INBUF,X'6E'         PA2: REPLAY THIS SCREEN
         BE    SCREEN
         LA    6,16(6)
         BCT   7,SCREEN
BACK     DS    0H
         STTMPMD OFF
         STFSMODE OFF
         STLINENO LINE=1
DONE     DS    0H
         L     13,SAVE+4
         LM    14,12,12(13)
         SR    15,15
         BR    14
SAVE     DC    18F'0'
HALFSEC  DC    F'50'
         LTORG
INBUF    DS    CL256
"""


def main():
    screens = [layout_screen('A', 1), layout_screen('B', 2), layout_screen('C', 3), gallery()]
    lines = HEAD.rstrip('\n').split('\n')
    lines.append(f'NSCRN    EQU   {len(screens)}')
    lines.append('SCRTAB   DS    0F')
    for k, (full, parts, _) in enumerate(screens, 1):
        lines.append(f'         DC    A(S{k}),A(S{k}L),A(T{k}),A({len(parts)})')
    for k, (full, parts, _) in enumerate(screens, 1):
        lines.append(f'T{k}       DS    0F')
        for p in range(len(parts)):
            lines.append(f'         DC    A(S{k}P{p}),A(S{k}P{p}L)')
    for k, (full, parts, n) in enumerate(screens, 1):
        lines += dc_lines(f'S{k}', full) + [f'S{k}L     EQU   *-S{k}']
        for p, part in enumerate(parts):
            lines += dc_lines(f'S{k}P{p}', part) + [f'S{k}P{p}L{" " * (4 - len(str(p)))}EQU   *-S{k}P{p}']
    lines.append('         END')
    (R / 'src/probe/PACFSB.asm').write_text('\n'.join(lines) + '\n', encoding='ascii')
    for k, (full, parts, n) in enumerate(screens, 1):
        print(f'screen {k}: renderer stream {n} bytes (FULLSCR sent {len(full)}), partials {[len(p) for p in parts]}')


if __name__ == '__main__':
    main()
