#!/usr/bin/env python3
"""Generates src/probe/PACS1A.asm (MVS-S1 probe E15: is the 3270 WCC alarm audible through the live c3270 path?).
Isolated from PACMAN. The alarm writes go through the UNCHANGED production service PACFSIO (assembled from
src/asm/PACFSIO.asm), with each send op the game uses for a screen:
  1. SENX  X'F5' Erase/Write, WCC C3 (no alarm)      control screen: no bell expected
  2. SENX  X'F5' Erase/Write, WCC C7 (C3 + alarm)    GS full screens (PACSCR WCC C3)
  3. SEND  TPUT FULLSCR, WCC C7                      G1-G4 full screens (PACFSIO adds the clear prefix)
  4. SENP  X'F1' Write (partial), WCC C7             G3/RT partial frames
  5. SENP  three alarm writes back to back           data for MVS-S2 only: are bells merged?
  6. SENP  three alarm writes 0.5 s apart            data for MVS-S2 only
X'7E' Erase/Write Alternate is not tested separately: c3270 checks the alarm bit in the WCC, whatever the command.
No Read Partition Query is sent, so the D28 hold does not apply. Each screen has a one-character input field: the user
types what was heard (Y/N on screens 1-4, the number of bells 0-3 on screens 5-6) and presses ENTER. The answers come
back to PACS1P, which prints them after line mode is restored. PA2 resends the current step (alarm included); PF3 stops.
WCC bits (GA23-0059): X'04' sound alarm, X'02' keyboard restore, X'01' reset MDT; C3 | 04 = C7, C2 | 04 = C6.
Usage: python3 tools/gen_probe_e15.py   (writes src/probe/PACS1A.asm)"""
from pathlib import Path

R = Path(__file__).resolve().parent.parent
CODES = [0x40, 0xC1, 0xC2, 0xC3, 0xC4, 0xC5, 0xC6, 0xC7, 0xC8, 0xC9, 0x4A, 0x4B, 0x4C, 0x4D, 0x4E, 0x4F,
         0x50, 0xD1, 0xD2, 0xD3, 0xD4, 0xD5, 0xD6, 0xD7, 0xD8, 0xD9, 0x5A, 0x5B, 0x5C, 0x5D, 0x5E, 0x5F,
         0x60, 0x61, 0xE2, 0xE3, 0xE4, 0xE5, 0xE6, 0xE7, 0xE8, 0xE9, 0x6A, 0x6B, 0x6C, 0x6D, 0x6E, 0x6F,
         0xF0, 0xF1, 0xF2, 0xF3, 0xF4, 0xF5, 0xF6, 0xF7, 0xF8, 0xF9, 0x7A, 0x7B, 0x7C, 0x7D, 0x7E, 0x7F]
SBA, SF, IC, SA = 0x11, 0x1D, 0x13, 0x28
PROT, INPUT = 0x60, 0xC8                     # protected / unprotected intensified field attributes
WCC_PLAIN, WCC_ALARM, WCC_BELL_ONLY = 0xC3, 0xC7, 0xC6
FIELD = (7, 21)                              # the answer position

YN = 'BELL HEARD? (Y/N):'
CNT = 'BELLS HEARD (0-3):'
STEPS = [
    ('SENX', 'FULL', WCC_PLAIN, YN, 0, 0,
     ['SCREEN 1 OF 6 - CONTROL: ERASE/WRITE (F5), WCC C3, NO ALARM BIT.',
      'NO BELL IS EXPECTED HERE. ANSWER N UNLESS YOU HEARD ONE.']),
    ('SENX', 'FULL', WCC_ALARM, YN, 0, 0,
     ['SCREEN 2 OF 6 - ERASE/WRITE (F5), WCC C7 = C3 + ALARM.',
      'THE PATH OF THE GS FULL SCREENS (PACFSIO SENX). LISTEN FOR ONE BELL.']),
    ('SEND', 'FULL', WCC_ALARM, YN, 0, 0,
     ['SCREEN 3 OF 6 - TPUT FULLSCR, WCC C7 = C3 + ALARM.',
      'THE PATH OF THE G1-G4 FULL SCREENS (PACFSIO SEND). LISTEN FOR ONE BELL.']),
    ('SENP', 'PART', WCC_ALARM, YN, 0, 0,
     ['SCREEN 4 OF 6 - PARTIAL WRITE (F1), WCC C7 = C3 + ALARM.',
      'THE PATH OF THE G3/REALTIME FRAMES (PACFSIO SENP). LISTEN FOR ONE BELL.']),
    ('SENP', 'PART', WCC_ALARM, CNT, 2, 0,
     ['SCREEN 5 OF 6 - THREE ALARM WRITES BACK TO BACK (NO DELAY).',
      'COUNT THE BELLS (0-3). DATA FOR A LATER PHASE (S2) ONLY.']),
    ('SENP', 'PART', WCC_ALARM, CNT, 2, 50,
     ['SCREEN 6 OF 6 - THREE ALARM WRITES 0.5 SECOND APART.',
      'COUNT THE BELLS (0-3). DATA FOR A LATER PHASE (S2) ONLY.']),
]
TITLE = 'PACMAN S1 PROBE E15 - 3270 ALARM (WCC BIT 04). ISOLATED, NOT THE GAME.'
HELP = 'TYPE YOUR ANSWER, THEN ENTER.  PA2 = RESEND THIS STEP.  PF3 = STOP.'


def stream(op, kind, wcc, question, lines):
    ds = bytearray()

    def sba(r, c):
        a = (r - 1) * 80 + (c - 1)
        ds.extend([SBA, CODES[a >> 6], CODES[a & 63]])

    def txt(s, width=None):
        ds.extend((s.ljust(width) if width else s).encode('cp037'))

    if op == 'SENX':
        ds.append(0xF5)                          # Erase/Write; SEND and SENP get their command from TSO / PACFSIO
    ds.append(wcc)
    if kind == 'FULL':
        sba(1, 1); ds.extend([SF, PROT]); txt(TITLE)
        sba(9, 2); txt(HELP)
    for i, s in enumerate(lines):
        sba(3 + i, 2); txt(s, 78)
    sba(7, 2); txt(question)
    if kind == 'FULL':
        sba(7, 20); ds.extend([SF, INPUT])
        sba(7, 22); ds.extend([SF, PROT])
    sba(*FIELD); ds.append(0x00); sba(*FIELD); ds.append(IC)
    return bytes(ds)


def dc_lines(label, data):
    out = [f'{label:<8} DS    0C']
    for k in range(0, len(data), 24):
        out.append(f"         DC    X'{data[k:k + 24].hex().upper()}'")
    out.append(f'{label}L EQU   *-{label}')
    return out


def program():
    a = []
    w = a.append
    for s in ['*        PACS1A : MVS-S1 PROBE E15 - IS THE 3270 WCC ALARM AUDIBLE',
              '*        THROUGH THE LIVE C3270 PATH? GENERATED BY',
              '*        TOOLS/GEN_PROBE_E15.PY (DO NOT EDIT BY HAND).',
              '*        CALL PACS1A USING RC ANS NSCR (FROM PACS1P)',
              '*          RC   S9(4) COMP  0 DONE, 4 NOT TSO, ELSE PACFSIO RC',
              '*          ANS  X(6)        ONE ANSWER PER SCREEN, - = NONE',
              '*          NSCR S9(4) COMP  SCREENS ANSWERED',
              '*        ALL TERMINAL I/O GOES THROUGH THE PRODUCTION PACFSIO',
              '*        (FSON, SENX, SEND, SENP, RECV, FSOF), UNCHANGED.',
              'PACS1A   CSECT',
              '         STM   14,12,12(13)',
              '         BALR  12,0',
              '         USING *,12',
              '         ST    13,SAVE+4',
              '         LA    14,SAVE',
              '         ST    14,8(13)',
              '         LR    13,14',
              '         LM    2,4,0(1)            RC ANS NSCR',
              '         LA    2,0(2)',
              '         LA    3,0(3)',
              '         LA    4,0(4)',
              "         MVC   0(6,3),=C'------'",
              '         SR    0,0',
              '         STH   0,0(4)',
              "         MVC   OP,=C'FSON'",
              '         BAL   11,FSIO',
              '         LTR   6,6',
              '         BNZ   NOFS                NOT TSO: NOTHING WAS SENT']:
        w(s)
    for n, (op, kind, wcc, q, extra, gap, lines) in enumerate(STEPS, 1):
        w(f'S{n}       DS    0H')
        w(f"         MVC   OP,=C'{op}'")
        w(f'         LA    7,DS{n}')
        w(f'         LA    8,DS{n}L')
        w('         BAL   9,SENDDS')
        for _ in range(extra):
            if gap:
                w('         STIMER WAIT,BINTVL=GAP')
            w("         MVC   OP,=C'SENP'")
            w('         LA    7,BELL')
            w('         LA    8,BELLL')
            w('         BAL   9,SENDDS')
        w('         BAL   10,GETANS')
        w("         CLI   AID,X'6E'           PA2: RESEND THIS STEP")
        w(f'         BE    S{n}')
        w("         CLI   AID,X'F3'           PF3: STOP")
        w('         BE    FINISH')
        w(f'         MVC   {n - 1}(1,3),ANSCH')
        w('         LH    0,0(4)')
        w("         AH    0,=H'1'")
        w('         STH   0,0(4)')
    for s in ['FINISH   DS    0H',
              "         MVC   OP,=C'FSOF'",
              '         BAL   11,FSIO',
              '         LH    6,ERRC              FIRST SEND/RECV ERROR, ELSE 0',
              'NOFS     DS    0H',
              '         STH   6,0(2)',
              '         L     13,SAVE+4',
              '         LM    14,12,12(13)',
              '         SR    15,15',
              '         BR    14',
              '*        SENDDS: SEND R8 BYTES AT R7 WITH THE OP IN OP (LINK R9)',
              'SENDDS   DS    0H',
              '         ST    7,PLIST+4',
              '         STH   8,LEN',
              '         BAL   11,FSIO',
              '         LTR   6,6',
              '         BZR   9',
              '         B     FAIL',
              '*        GETANS: RECV ONE INBOUND RECORD, AID AND ANSWER (LINK R10)',
              '*        RECORD = AID, CURSOR(2), SBA(3) + TYPED DATA IF ANY',
              'GETANS   DS    0H',
              "         MVC   OP,=C'RECV'",
              '         LA    7,INBUF',
              '         ST    7,PLIST+4',
              '         BAL   11,FSIO',
              '         LTR   6,6',
              '         BNZ   FAIL                NO INPUT IN 5 MINUTES OR ERROR',
              '         MVC   AID,INBUF',
              "         MVI   ANSCH,C'-'",
              '         LH    0,LEN',
              "         CH    0,=H'7'",
              '         BLR   10',
              "         CLI   INBUF+3,X'11'",
              '         BNER  10',
              '         MVC   ANSCH,INBUF+6',
              '         BR    10',
              'FAIL     DS    0H',
              '         STH   6,ERRC',
              '         B     FINISH',
              '*        FSIO: CALL PACFSIO USING OP BUF LEN RC (LINK R11), R6 = RC',
              'FSIO     DS    0H',
              '         LA    1,PLIST',
              '         L     15,=V(PACFSIO)',
              '         BALR  14,15',
              '         LH    6,RC',
              '         BR    11',
              'SAVE     DC    18F\'0\'',
              'PLIST    DC    A(OP)',
              '         DC    A(INBUF)',
              '         DC    A(LEN)',
              '         DC    X\'80\',AL3(RC)',
              "OP       DC    CL4' '",
              "LEN      DC    H'0'",
              "RC       DC    H'0'",
              "ERRC     DC    H'0'",
              "AID      DC    X'00'",
              "ANSCH    DC    C'-'",
              "GAP      DC    F'50'               0.5 S (1/100 S UNITS)",
              '         LTORG']:
        w(s)
    for n, (op, kind, wcc, q, extra, gap, lines) in enumerate(STEPS, 1):
        a.extend(dc_lines(f'DS{n}', stream(op, kind, wcc, q, lines)))
    a.extend(dc_lines('BELL', bytes([WCC_BELL_ONLY, SA, 0x00, 0x00])))   # alarm + restore only, as the RT restore write
    a += ['INBUF    DS    CL2048              ONLY ITS START NEEDS R12', '         END']
    return '\n'.join(a) + '\n'


if __name__ == '__main__':
    assert all(STEPS[i][5] in (0, 50) for i in range(len(STEPS)))
    dest = R / 'src/probe/PACS1A.asm'
    dest.write_text(program(), encoding='ascii')
    for n, s in enumerate(STEPS, 1):
        print(f'screen {n}: {s[0]} {len(stream(s[0], s[1], s[2], s[3], s[6]))} bytes, WCC {s[2]:02X}, +{s[4]} bell writes')
    print(dest)
