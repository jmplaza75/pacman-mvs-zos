#!/usr/bin/env python3
"""R3 gate (ZOS-2, docs/ZOS-MIGRATION-PLAN.md R3): the MVS target of tools/make_deck.py is unchanged.

Usage: r3_gate.py [--ref zos-1]
1. The 13 release decks of record (releases/2.0-MVS-MAX/decks) regenerated with their MANIFEST commands: SHA-256 equal
   to releases/2.0-MVS-MAX/SHA256SUMS.
2. Every MVS deck make_deck.py offers (default prefix, with and without --runonly) generated by the current tree and by
   the tree at --ref (git archive, read-only): byte-identical.
Exit 1 on any difference. Nothing is written outside a temporary directory.
"""
import argparse
import hashlib
import re
import subprocess
import sys
import tempfile
from pathlib import Path

R = Path(__file__).resolve().parent.parent.parent
R20, INST = 'HERC01.PACMAN.R20', 'HERC01.PACMAN'
RELEASE = [('R20-ALLOC', ['ALLOC', '--prefix', R20]), ('R20-CLIST', ['CLIST', '--prefix', R20]),
           ('R20-REL20', ['REL20', '--prefix', R20])] + \
          [(f'R20-{d}', [d, '--runonly', '--load', 'PACMAIN', '--prefix', R20]) for d in ('S2', 'RP', 'GP2', 'GP23', 'HS')] + \
          [('INST20', ['INST20', '--source', R20, '--prefix', INST]), ('INST-CLIST', ['CLIST', '--prefix', INST]),
           ('DATA', ['DATA', '--prefix', INST]), ('INST-ORACLE', ['RELEASE', '--runonly', '--prefix', INST]),
           ('INST-S2', ['S2', '--runonly', '--load', 'PACMAIN', '--prefix', INST])]


def gen(root, args, out):
    r = subprocess.run([sys.executable, str(root / 'tools/make_deck.py'), *args, '--out', str(out)],
                       capture_output=True, text=True)
    return r.returncode, (r.stderr.strip().splitlines() or [''])[-1]


def choices(root):
    r = subprocess.run([sys.executable, str(root / 'tools/make_deck.py'), '--help'], capture_output=True, text=True)
    sets = re.findall(r'\{([^}]*)\}', ''.join(r.stdout.split()))
    return next(x.split(',') for x in sets if 'ALLOC' in x.split(','))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--ref', default='zos-1')
    a = ap.parse_args()
    bad = 0
    sums = {l.split()[1]: l.split()[0] for l in (R / 'releases/2.0-MVS-MAX/SHA256SUMS').read_text().splitlines() if l}
    with tempfile.TemporaryDirectory() as t:
        t = Path(t)
        for name, args in RELEASE:
            rc, err = gen(R, args, t / f'{name}.jcl')
            key = f'releases/2.0-MVS-MAX/decks/{name}.jcl'
            got = hashlib.sha256((t / f'{name}.jcl').read_bytes()).hexdigest() if rc == 0 else err
            ok = got == sums[key]
            bad += not ok
            print(f'{"OK  " if ok else "DIFF"} release {name:<12} {got[:16]}')
        old = t / 'ref'
        old.mkdir()
        prefix = subprocess.run(['git', 'rev-parse', '--show-prefix'], cwd=R, capture_output=True, text=True,
                                check=True).stdout.strip()
        top = subprocess.run(['git', 'rev-parse', '--show-toplevel'], cwd=R, capture_output=True, text=True,
                             check=True).stdout.strip()
        arc = subprocess.run(['git', 'archive', a.ref, prefix], cwd=top, capture_output=True, check=True).stdout
        subprocess.run(['tar', '-x', '-C', str(old)], input=arc, check=True)
        oldroot = old / prefix
        names = choices(oldroot)
        assert names == choices(R), 'MVS deck list changed'
        n = 0
        for d in names:
            for extra in ([], ['--runonly']):
                rc1, e1 = gen(oldroot, [d, *extra], t / 'a.jcl')
                rc2, e2 = gen(R, [d, *extra], t / 'b.jcl')
                same = (rc1, e1) == (rc2, e2) and (rc1 != 0 or (t / 'a.jcl').read_bytes() == (t / 'b.jcl').read_bytes())
                n += 1
                if not same:
                    bad += 1
                    print(f'DIFF mvs {d} {" ".join(extra)} (ref rc {rc1} {e1} / now rc {rc2} {e2})')
                for f in ('a.jcl', 'b.jcl'):
                    (t / f).unlink(missing_ok=True)
        print(f'{n} MVS deck generations compared with {a.ref}')
    print('R3 GATE ' + ('PASS' if not bad else f'FAIL ({bad})'))
    sys.exit(1 if bad else 0)


if __name__ == '__main__':
    main()
