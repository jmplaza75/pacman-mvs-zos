#!/usr/bin/env python3
"""Generates src/probe/PACFS9.asm (MVS-G4 probe E9: APL / graphic character set).
One full screen (TPUT FULLSCR, clear prefix as in D25, unformatted) shows:
 rows 4-15  the 192 code points X'40'-X'FF' of the second character set twice: left with the GE order (X'08' before
            every byte), right with the character-set attribute SA X'43' X'F1' (LCID F1 as announced by the x3270
            family) around the whole row; labels and headers are plain base-set text;
 rows 17-20 the same mini maze as wall tiles: left APL box pieces via GE, right base-set tiles (+ - | and middle dot);
 row 21     base-set (CP037) candidates for a profile without GE.
Order = the game's (G1-G3): Read Partition Query (TPUT NOEDIT), its reply (AID X'88', returned whole so QCode X'85'
can be decoded), THEN the screen, then a key (PA2 redraws, anything else ends). The first live run sent the screen
before the query: the Query Reply locks the 3270 keyboard and nothing restored it (X Wait, ENTER queued in c3270).
Usage: python3 tools/gen_probe_e9.py   (writes src/probe/PACFS9.asm and prints the expected grid as Unicode)"""
from pathlib import Path

R = Path(__file__).resolve().parent.parent
CODES = [0x40, 0xC1, 0xC2, 0xC3, 0xC4, 0xC5, 0xC6, 0xC7, 0xC8, 0xC9, 0x4A, 0x4B, 0x4C, 0x4D, 0x4E, 0x4F,
         0x50, 0xD1, 0xD2, 0xD3, 0xD4, 0xD5, 0xD6, 0xD7, 0xD8, 0xD9, 0x5A, 0x5B, 0x5C, 0x5D, 0x5E, 0x5F,
         0x60, 0x61, 0xE2, 0xE3, 0xE4, 0xE5, 0xE6, 0xE7, 0xE8, 0xE9, 0x6A, 0x6B, 0x6C, 0x6D, 0x6E, 0x6F,
         0xF0, 0xF1, 0xF2, 0xF3, 0xF4, 0xF5, 0xF6, 0xF7, 0xF8, 0xF9, 0x7A, 0x7B, 0x7C, 0x7D, 0x7E, 0x7F]
GE, SA, COLOR, CSET, APL = 0x08, 0x28, 0x42, 0x43, 0xF1
BLUE, RED, GREEN, TURQ, YELLOW, WHITE = 0xF1, 0xF2, 0xF4, 0xF5, 0xF6, 0xF7
ds = bytearray()


def sba(r, c):
    a = (r - 1) * 80 + (c - 1)
    ds.extend([0x11, CODES[a >> 6], CODES[a & 63]])


def col(v):
    ds.extend([SA, COLOR, v])


def txt(s):
    ds.extend(s.encode('cp037'))


# maze tiles (CP310 code points) and their base-set twins
GE_MAZE = ['C5 A2 A2 A2 A2 D7 A2 A2 A2 A2 D5', '85 A3 9B 40 9D 85 AA 40 A3 40 85',
           'C6 A2 A2 A2 A2 D3 A2 A2 A2 A2 D6', 'C4 A2 A2 A2 A2 C7 A2 A2 A2 A2 D4']
BASE_MAZE = ['+----+----+', '|' + '\xb7' + 'C O|G ' + '\xb7' + ' |', '+----+----+', '+----+----+']
TILE_COL = {0xA3: WHITE, 0x9B: YELLOW, 0x9D: YELLOW, 0xAA: RED, 0x40: BLUE}

ds.append(0xC3)                                         # WCC: reset, keyboard restore, reset MDT
sba(1, 1); ds.extend([0x3C, 0x40, 0x40, 0x00])          # clear prefix (D25)
sba(1, 2); col(TURQ); txt('PACMAN G4 PROBE E9 - SECOND CHARACTER SET (APL, CP310)')
sba(2, 2); col(GREEN); txt('LEFT: GE ORDER 08 BEFORE EACH BYTE     RIGHT: SA 43 F1 (CHARSET F1)')
for base in (6, 48):
    sba(3, base - 4); col(GREEN); txt('   ' + ' '.join('0123456789ABCDEF'))
for hi in range(4, 16):
    row = hi
    sba(row, 2); col(GREEN); txt(f'{hi:X}X')
    sba(row, 6); col(WHITE)
    for lo in range(16):
        ds.extend([GE, hi * 16 + lo])
        if lo < 15:
            ds.append(0x40)
    sba(row, 44); col(GREEN); txt(f'{hi:X}X')
    sba(row, 48); col(WHITE); ds.extend([SA, CSET, APL])
    for lo in range(16):
        ds.append(hi * 16 + lo)
        if lo < 15:
            ds.append(0x40)
    ds.extend([SA, CSET, 0x00])
for i, (g, b) in enumerate(zip(GE_MAZE, BASE_MAZE)):
    sba(17 + i, 2); col(GREEN); txt('APL ' if i == 0 else '    ')
    cur = None
    for v in (int(x, 16) for x in g.split()):
        c = TILE_COL.get(v, BLUE)
        if c != cur:
            col(c); cur = c
        ds.extend([GE, v])
    sba(17 + i, 44); col(GREEN); txt('BASE' if i == 0 else '    ')
    sba(17 + i, 48); cur = None
    for ch in b:
        c = {'\xb7': WHITE, 'C': YELLOW, 'O': YELLOW, 'G': RED}.get(ch, BLUE)
        if c != cur:
            col(c); cur = c
        ds.extend(ch.encode('cp037'))
sba(21, 2); col(GREEN); txt('BASE CP037 CANDIDATES B3 90 9F 6A 5F BC 9B 8A 8B AF B4 4F:')
sba(21, 61); col(WHITE)
for v in (0xB3, 0x90, 0x9F, 0x6A, 0x5F, 0xBC, 0x9B, 0x8A, 0x8B, 0xAF, 0xB4, 0x4F):
    ds.extend([v, 0x40])
sba(23, 2); col(GREEN); txt('NOTE WHAT YOU SEE (BOTH GRIDS, MAZES, ROW 21); THEN ENTER. PA2 = REDRAW')
ds.extend([SA, 0x00, 0x00]); sba(24, 2); ds.append(0x13)  # reset attributes, insert cursor


def dc_lines(label, data):
    out, first = [], True
    for k in range(0, len(data), 24):
        chunk = data[k:k + 24]
        out.append(f"{label if first else '':<8} DC    X'{chunk.hex().upper()}'")
        first = False
    return out


HEAD = """*        PACFS9 : MVS-G4 PROBE E9 (GENERATED BY TOOLS/GEN_PROBE_E9.PY,
*        DO NOT EDIT). ONE FULL SCREEN WITH THE SECOND CHARACTER SET
*        (GE ORDER AND SA X'43') AND WALL TILE SAMPLES. ORDER (AS IN
*        THE GAME): READ PARTITION QUERY, ITS REPLY (RETURNED WHOLE),
*        THEN THE SCREEN (WCC C3 UNLOCKS THE KEYBOARD), THEN A KEY.
*        CALL 'PACFS9' USING QBUF QLEN RC AID NSCR
*          QBUF X(1024) QUERY REPLY (AID X'88' ...), QLEN S9(4) COMP
*          ITS LENGTH (0 = NO REPLY), RC S9(4) COMP LAST TPUT/TGET RC
*          (4 = NOT A TSO SESSION), AID X(1) FINAL KEY (X'00' NONE),
*          NSCR S9(4) COMP SCREENS SENT (1 + PA2 REDRAWS)
PACFS9   CSECT
         STM   14,12,12(13)
         BALR  12,0
         USING *,12,11
         LA    11,2048(12)
         LA    11,2048(11)
         ST    13,SAVE+4
         LA    14,SAVE
         ST    14,8(13)
         LR    13,14
         LM    2,6,0(1)
         LA    2,0(2)
         LA    3,0(3)
         LA    4,0(4)
         LA    5,0(5)
         LA    6,0(6)
         SR    7,7
         STH   7,0(3)
         STH   7,0(6)
         MVI   0(5),X'00'
         LA    7,4
         STH   7,0(4)
         L     1,X'224'            PSAAOLD: CURRENT ASCB
         L     1,X'3C'(1)          ASCBTSB: ZERO UNLESS TSO USER
         LTR   1,1
         BZ    DONE
         TCLEARQ OUTPUT
         TCLEARQ INPUT
         STFSMODE ON,INITIAL=YES
         STTMPMD ON
         LA    1,QUERY
         L     0,=A(QUERYL)
         TPUT  (1),(0),NOEDIT
         STH   15,0(4)
         LTR   15,15
         BNZ   BACK
         SR    8,8                 EMPTY READS
QREAD    DS    0H
         LR    1,2
         L     0,=F'1024'
         TGET  (1),(0),ASIS
         STH   15,0(4)
         LTR   1,1
         BNZ   QGOT
         LA    8,1(8)
         C     8,=F'10'
         BNL   SHOW                NO REPLY WITHIN 5 S
         STIMER WAIT,BINTVL=HALFSEC
         B     QREAD
QGOT     DS    0H
         CLI   0(2),X'88'
         BNE   NOTQRY
         STH   1,0(3)
         B     SHOW
NOTQRY   DS    0H
         MVC   0(1,5),0(2)         A KEY CAME FIRST: NO REPLY
         CLI   0(2),X'6E'
         BNE   BACK
SHOW     DS    0H                  SCREEN AFTER THE REPLY (GAME
         BAL   10,SENDSCR          ORDER): WCC C3 RESTORES THE
         LTR   15,15               KEYBOARD LOCKED BY THE REPLY
         BNZ   BACK
KEYS     DS    0H
         SR    8,8
KREAD    DS    0H
         LA    1,INBUF
         L     0,=F'256'
         TGET  (1),(0),ASIS
         STH   15,0(4)
         LTR   1,1
         BNZ   KGOT
         LA    8,1(8)
         C     8,=F'600'
         BNL   BACK                5 MINUTES WITHOUT A KEY
         STIMER WAIT,BINTVL=HALFSEC
         B     KREAD
KGOT     DS    0H
         MVC   0(1,5),INBUF
         CLI   INBUF,X'6E'         PA2: REDRAW AND WAIT AGAIN
         BNE   BACK
         BAL   10,SENDSCR
         LTR   15,15
         BNZ   BACK
         B     KEYS
SENDSCR  DS    0H
         LH    7,0(6)
         LA    7,1(7)
         STH   7,0(6)
         LA    1,SCREEN
         L     0,=A(SCREENL)
         TPUT  (1),(0),FULLSCR
         STH   15,0(4)
         BR    10
BACK     DS    0H
         STTMPMD OFF
         STFSMODE OFF
         STLINENO LINE=1
DONE     DS    0H
         L     13,SAVE+4
         LM    14,12,12(13)
         SR    15,15
         BR    14
SAVE     DC    18F'0'
HALFSEC  DC    F'50'
QUERY    DC    X'F3000501FF02'
QUERYL   EQU   *-QUERY
         LTORG
INBUF    DS    CL256
"""

lines = HEAD.rstrip('\n').split('\n') + dc_lines('SCREEN', bytes(ds))
lines += ['SCREENL  EQU   *-SCREEN', '         END']
(R / 'src/probe/PACFS9.asm').write_text('\n'.join(lines) + '\n', encoding='ascii')
print(f'src/probe/PACFS9.asm written, screen {len(ds)} bytes')
