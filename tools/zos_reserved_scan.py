DIVISION_WORDS = {'IDENTIFICATION', 'ENVIRONMENT', 'DATA', 'PROCEDURE', 'WORKING-STORAGE', 'LINKAGE', 'FILE',
                  'CONFIGURATION', 'INPUT-OUTPUT', 'FILE-CONTROL', 'PROGRAM-ID', 'AUTHOR', 'SPECIAL-NAMES'}


def names(path):
    out = []
    for n, raw in enumerate(path.read_text(errors='replace').splitlines(), 1):
        if len(raw) < 8 or raw[6:7] in ('*', '/'):
            continue
        code = raw[7:72]
        m = re.match(r'\s*\d\d\s+([A-Z0-9][A-Z0-9-]*)', code)
        if m and m.group(1) != 'FILLER':
            out.append((n, m.group(1), 'data'))
        m = re.match(r'([A-Z0-9][A-Z0-9-]*)(\s+SECTION)?\s*\.\s*$', code)     # area A paragraph / section
        if m and m.group(1) not in DIVISION_WORDS and not code.startswith(' '):
            out.append((n, m.group(1), 'paragraph'))
        for kw in ('SELECT', 'FD', 'PROGRAM-ID.'):
            m = re.search(r'\b' + re.escape(kw) + r'\s+([A-Z0-9][A-Z0-9-]*)', code)
            if m:
                out.append((n, m.group(1), kw.rstrip('.').lower()))
    return out


def main():
    files = [Path(f) for f in sys.argv[1:]] or sorted(
        list((R / 'src/cobol').glob('*.cob')) + list((R / 'src/copy').glob('*.cpy')) + list((R / 'src/probe').glob('*.cob')))
    total, hits = 0, []
    for f in files:
        for n, name, kind in names(f):
            total += 1
            if name in RESERVED:
                hits.append(f'{f.relative_to(R) if f.is_absolute() else f}:{n}: {kind} name {name} is reserved')
    print('\n'.join(hits))
    print(f'{len(files)} files, {total} user-defined names, {len(hits)} reserved-word hits '
          f'({len(RESERVED)} Enterprise COBOL words checked)')
    sys.exit(1 if hits else 0)


if __name__ == '__main__':
    main()
